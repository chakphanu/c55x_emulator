/* Render s at column x (6 columns per character); returns the column after the text. */
int text_render(unsigned int *columns, int x, const char *s)
{
    int i;
    unsigned int c;

    for (; *s != 0 && x + 5 <= LCD_WIDTH; s++) {
        c = (unsigned int)*s;
        for (i = 0; i < 5; i++) {
            columns[x + i] = (c >= FIRST && c <= LAST) ? glyphs[c - FIRST][i] : 0;
        }
        x += 6;
    }
    return x;
}

/* Write value as 'digits' upper-case hex digits; returns the end (not terminated). */
char *hex_put(char *out, unsigned int value, int digits)
{
    int i;

    for (i = digits - 1; i >= 0; i--) {
        out[i] = "0123456789ABCDEF"[value & 15];
        value >>= 4;
    }
    return out + digits;
}
